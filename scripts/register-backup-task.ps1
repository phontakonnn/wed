<#
.SYNOPSIS
  Registers the daily PKH backup task in Windows Task Scheduler.

.DESCRIPTION
  Writes scripts\backup-config.cmd (untracked) with the DATA_DIR / BACKUP_DIR you pass in,
  then registers a daily task that runs scripts\backup-daily.cmd.

  Logon type:
    S4U            - runs whether or not the user is logged on, no password stored.
                     Preferred, but some group policies require elevation to register it.
    Interactive    - fallback; runs only while the user is logged on.

  This script changes NOTHING about the server, authentication, or the database.

.EXAMPLE
  .\scripts\register-backup-task.ps1 -DataDir 'C:\PKH-data' -BackupDir 'E:\PKH-backups' -Time '02:00'

.NOTES
  Verify BK-08 (separate physical disk) before pointing BACKUP_DIR at a volume.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$DataDir,
    [Parameter(Mandatory = $true)][string]$BackupDir,
    [string]$Time = '02:00',
    [string]$TaskName = 'PKH Backup'
)

$ErrorActionPreference = 'Stop'

function Assert-AbsolutePath {
    param([string]$Name, [string]$Path)
    if (-not [System.IO.Path]::IsPathRooted($Path)) {
        throw "$Name must be an absolute path (got: $Path)"
    }
}

Assert-AbsolutePath -Name 'DataDir' -Path $DataDir
Assert-AbsolutePath -Name 'BackupDir' -Path $BackupDir

$repoRoot = Split-Path -Parent $PSScriptRoot
$dailyScript = Join-Path $PSScriptRoot 'backup-daily.cmd'
if (-not (Test-Path $dailyScript)) { throw "Missing wrapper script: $dailyScript" }

# Refuse to schedule a backup into the same directory as the live database.
if ([System.IO.Path]::GetFullPath($BackupDir).TrimEnd('\') -eq [System.IO.Path]::GetFullPath($DataDir).TrimEnd('\')) {
    throw 'BACKUP_DIR must not be the DATA_DIR itself.'
}

# A nested destination is usable but fails the separate-disk gate; make that explicit.
if ([System.IO.Path]::GetFullPath($BackupDir).StartsWith([System.IO.Path]::GetFullPath($DataDir).TrimEnd('\') + '\')) {
    Write-Warning 'BACKUP_DIR is inside DATA_DIR. This does not satisfy BK-08 (separate physical disk).'
}
if (-not (Test-Path -LiteralPath $BackupDir)) {
    Write-Warning "BACKUP_DIR does not exist yet: $BackupDir. Create it before the first scheduled run."
}
if ($env:BACKUP_ENCRYPTION_REQUIRED -eq 'true' -and -not $env:BACKUP_ENCRYPTION_KEY) {
    Write-Warning 'BACKUP_ENCRYPTION_REQUIRED=true but BACKUP_ENCRYPTION_KEY is not set in this session. The task account must have the key or every run will fail closed.'
} elseif (-not $env:BACKUP_ENCRYPTION_REQUIRED) {
    Write-Warning 'Encryption is not required. Set BACKUP_ENCRYPTION_REQUIRED=true and a key for the task account before using real data.'
}

# Read-only preflight. It never writes to DATA_DIR or BACKUP_DIR.
Push-Location $repoRoot
try {
    $env:DATA_DIR = $DataDir
    $env:BACKUP_DIR = $BackupDir
    & npm run backup:preflight
    if ($LASTEXITCODE -ne 0) {
        throw "Preflight failed (exit $LASTEXITCODE). Fix the configuration before registering the task."
    }
}
finally {
    Pop-Location
}

$configPath = Join-Path $PSScriptRoot 'backup-config.cmd'
$configBody = @"
@echo off
rem Generated by register-backup-task.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
set "DATA_DIR=$DataDir"
set "BACKUP_DIR=$BackupDir"
"@
Set-Content -Path $configPath -Value $configBody -Encoding ASCII
Write-Host "Wrote $configPath"

$action = New-ScheduledTaskAction -Execute 'cmd.exe' `
    -Argument "/c `"$dailyScript`"" `
    -WorkingDirectory $repoRoot
$trigger = New-ScheduledTaskTrigger -Daily -At $Time
$settings = New-ScheduledTaskSettingsSet `
    -StartWhenAvailable `
    -MultipleInstances IgnoreNew `
    -ExecutionTimeLimit (New-TimeSpan -Hours 1)

$userId = "$env:USERDOMAIN\$env:USERNAME"

try {
    $principal = New-ScheduledTaskPrincipal -UserId $userId -LogonType S4U -RunLevel Limited
    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
        -Settings $settings -Principal $principal -Force | Out-Null
    Write-Host "Registered '$TaskName' (S4U: runs while logged off)."
}
catch {
    Write-Warning "S4U registration failed: $($_.Exception.Message)"
    Write-Warning 'Falling back to Interactive logon (task runs only while you are logged on).'
    $principal = New-ScheduledTaskPrincipal -UserId $userId -LogonType Interactive -RunLevel Limited
    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
        -Settings $settings -Principal $principal -Force | Out-Null
    Write-Host "Registered '$TaskName' (Interactive)."
}

Write-Host ''
Write-Host 'Physical disk separation is NOT VERIFIED by this script.'
Write-Host 'Confirm the destination is a different physical disk before relying on these backups.'
Write-Host ''
Write-Host 'Verify with:'
Write-Host "  Get-ScheduledTask -TaskName '$TaskName' | Get-ScheduledTaskInfo"
Write-Host 'Test one run now:'
Write-Host "  Start-ScheduledTask -TaskName '$TaskName'"
Write-Host "  Get-Content '$DataDir\logs\backup.log' -Tail 20"
